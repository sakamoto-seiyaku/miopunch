#!/usr/bin/env python3
"""Build the declared Tauri Linux graph in a pinned native toolchain image.

One shared cache lease covers compilation and immutable pinning. Ubuntu's host
build scripts/proc macros require a newer libc than the Debian host, so this
toolchain has one stable cache leaf inside target/. An explicit Rust target
alone does not isolate host artifacts. No target tree is copied.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shlex
import subprocess
import tarfile
import time
import tomllib

from build_native_client import ROOT, input_paths as sdk_inputs
from cargo_cache import build_environment, cache_lease, cargo_command, disk_state
from pin_artifact import pin_artifact

IMAGE = "sha256:5bf4699470632ddf19a61a5e4d21795e30ffb3ef8a0f621d90137d27eedda942"
TOOLCHAIN = Path.home() / ".rustup/toolchains/stable-x86_64-unknown-linux-gnu"
APP = ROOT / "platform/desktop"
GENERATED = (APP / "gen", APP / "permissions/autogenerated")
ISOLATED_TARGET = ROOT / "target/.miopunch-toolchains/tauri-linux" / IMAGE.removeprefix("sha256:") / "cargo-target"
ISOLATION_REASON = "Ubuntu24.04 host build scripts/proc macros require GLIBC2.39; Debian host uses GLIBC2.36. Stable per-toolchain host cache, not per-run isolation."


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def inputs():
    names = sdk_inputs() | {"scripts/build_desktop_host.py"}
    for path in APP.rglob("*"):
        if path.is_file() and not any(path.is_relative_to(folder) for folder in GENERATED):
            names.add(path.relative_to(ROOT).as_posix())
    return {name: sha(ROOT / name) for name in sorted(names)}


def validate(expected, plan):
    if inputs() != expected:
        raise RuntimeError("desktop source precondition failed before Cargo")
    if sha(ROOT / "Cargo.lock") != plan["sdk_lock_sha256"] or sha(APP / "Cargo.lock") != plan["desktop_lock_sha256"]:
        raise RuntimeError("declared product locks changed")
    old = tomllib.loads((ROOT / "Cargo.lock").read_text())["package"]
    new = tomllib.loads((APP / "Cargo.lock").read_text())["package"]
    for name in {p["name"] for p in old} & {p["name"] for p in new}:
        before = {(p["version"], p.get("source"), p.get("checksum")) for p in old if p["name"] == name}
        after = {(p["version"], p.get("source"), p.get("checksum")) for p in new if p["name"] == name}
        if not before & after:
            raise RuntimeError("desktop graph replaced every SDK pin for " + name)
    version = subprocess.check_output(["rtk", "proxy", str(TOOLCHAIN / "bin/rustc"), "-Vv"], text=True)
    if version != plan["rustc"]:
        raise RuntimeError("desktop Rust toolchain changed")
    actual = subprocess.check_output(["rtk", "proxy", "docker", "image", "inspect", IMAGE, "--format", "{{.Id}}"], text=True).strip()
    if actual != plan["compiler_image"] or actual != IMAGE:
        raise RuntimeError("desktop compiler image changed")


def capture_desktop_depfiles(artifacts, output, expected, top):
    """Tauri emits directory sentinels for recursively embedded app assets/ACLs.

    Validate every member against the frozen source or declared generated
    outputs, and retain the directory membership separately from file hashes.
    """
    paths = {top} if top.is_file() else set()
    for artifact in artifacts:
        for filename in artifact["filenames"]:
            path = Path(filename)
            candidate = path.with_name(path.stem.removeprefix("lib") + ".d")
            if candidate.is_file():
                paths.add(candidate)
    if not paths:
        raise RuntimeError("desktop graph emitted no dependency information")
    selected, directories, depfiles = {}, {}, {}
    for path in sorted(paths):
        relative = path.relative_to(ROOT / "target")
        destination = output / "depfiles" / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        content = path.read_bytes()
        destination.write_bytes(content)
        depfiles[str(relative)] = hashlib.sha256(content).hexdigest()
        for line in content.decode().replace("\\\n", "").splitlines():
            if ": " not in line:
                continue
            for name in shlex.split(line.split(": ", 1)[1]):
                source = Path(name)
                if not source.is_absolute():
                    source = ROOT / source
                source = source.resolve()
                if not source.is_relative_to(ROOT) or source.is_relative_to(ROOT / "target"):
                    continue
                members = [source]
                if source.is_dir():
                    if not source.is_relative_to(APP):
                        raise RuntimeError("undeclared dependency directory: " + str(source))
                    members = sorted(p for p in source.rglob("*") if p.is_file())
                    directories[source.relative_to(ROOT).as_posix()] = [p.relative_to(ROOT).as_posix() for p in members]
                for member in members:
                    name = member.relative_to(ROOT).as_posix()
                    if name not in expected or sha(member) != expected[name]:
                        raise RuntimeError("selected desktop input was not frozen: " + name)
                    selected[name] = expected[name]
    return {"depfiles":depfiles, "selectedRepositoryInputs":selected, "selectedDirectories":directories}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inputs", type=Path, required=True)
    parser.add_argument("--plan", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    expected = json.loads(args.inputs.read_text())
    plan = json.loads(args.plan.read_text())
    assert sha(args.inputs) == plan["source_manifest_sha256"] and plan["decision"]
    validate(expected, plan)
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    (output / "inputs.json").write_text(json.dumps(expected, indent=2) + "\n")
    (output / "plan.json").write_bytes(args.plan.read_bytes())
    with tarfile.open(output / "source.tar.gz", "w:gz") as archive:
        for name in expected:
            archive.add(ROOT / name, arcname=name)
    shared = ROOT / "target"
    target = ISOLATED_TARGET
    environment = build_environment(target)
    report = {"exit": None, "platform": "x86_64-unknown-linux-gnu", "profile": "dev", "features": [],
        "compilerImage": IMAGE, "toolchain": plan["rustc"], "sdkLockSHA256": plan["sdk_lock_sha256"],
        "desktopLockSHA256": plan["desktop_lock_sha256"], "storeBudgetBytes": plan["store_cap"],
        "sharedTarget": str(shared), "graphTarget":str(target), "isolationReason":ISOLATION_REASON,
        "sourceArchiveSHA256": sha(output / "source.tar.gz")}
    try:
        with cache_lease(shared) as before:
            validate(expected, plan)
            target.mkdir(parents=True, exist_ok=True)
            used = sum(p.stat().st_blocks * 512 for p in (ROOT / ".artifacts/sha256").rglob("*") if p.is_file())
            if used != plan["allocated_before"] or used + plan["linux_pin_budget"] > plan["store_cap"]:
                raise RuntimeError("artifact retention precondition changed")
            report["diskBefore"] = before
            arguments = ["build", "--manifest-path", "platform/desktop/Cargo.toml", "--locked", "--offline",
                "--target", report["platform"], "--bin", "miopunch-desktop", "--jobs", "2"]
            cargo = cargo_command(arguments, target)[3:]
            command = ["rtk", "proxy", "docker", "run", "--rm", "--cidfile", str(output / "compiler.cid"), "--network", "none", "--user", f"{os.getuid()}:{os.getgid()}",
                "--entrypoint", str(TOOLCHAIN / "bin/cargo"), "-v", f"{ROOT}:{ROOT}",
                "-v", f"{Path.home() / '.cargo/registry'}:{Path.home() / '.cargo/registry'}:ro",
                "-v", f"{TOOLCHAIN}:{TOOLCHAIN}:ro", "-w", str(ROOT),
                "-e", f"PATH={TOOLCHAIN}/bin:/usr/bin:/bin", "-e", f"CARGO_HOME={Path.home() / '.cargo'}",
                "-e", f"CARGO_TARGET_DIR={target}", IMAGE, *cargo]
            report["command"] = command
            started = time.monotonic()
            with (output / "cargo.jsonl").open("w") as stdout, (output / "cargo.stderr.log").open("w") as stderr:
                completed = subprocess.run(command, cwd=ROOT, env=environment, stdout=stdout, stderr=stderr)
            report.update(exit=completed.returncode, seconds=time.monotonic() - started)
            messages = [json.loads(line) for line in (output / "cargo.jsonl").read_text().splitlines()]
            artifacts = [m for m in messages if m.get("reason") == "compiler-artifact"]
            report.update(freshArtifacts=sum(a["fresh"] for a in artifacts), rebuiltArtifacts=sum(not a["fresh"] for a in artifacts),
                rebuiltTargets=[{"package":a["package_id"],"target":a["target"]["name"]} for a in artifacts if not a["fresh"]])
            if completed.returncode:
                raise RuntimeError("desktop Cargo build failed; retain original compiler evidence")
            validate(expected, plan)
            generated = {p.relative_to(ROOT).as_posix(): sha(p) for folder in GENERATED for p in folder.rglob("*") if p.is_file()}
            (output / "generated-output-hashes.json").write_text(json.dumps(generated, indent=2) + "\n")
            binary = target / report["platform"] / "debug/miopunch-desktop"
            selected = capture_desktop_depfiles(artifacts, output, expected | generated, binary.with_suffix(".d"))
            (output / "selected-dependency-inputs.json").write_text(json.dumps(selected, indent=2) + "\n")
            if binary.stat().st_size > plan["linux_pin_budget"]:
                raise RuntimeError("desktop executable exceeds its declared reservation")
            report["pin"] = str(pin_artifact(binary, ROOT / ".artifacts/runs" / output.name / "miopunch-desktop", max_bytes=plan["store_cap"]))
            report["sha256"] = sha(binary)
            report["diskAfter"] = disk_state(shared)
            if report["diskAfter"]["cacheBytes"] - plan.get("cache_baseline_bytes", before["cacheBytes"]) > plan["cache_growth_budget"]:
                raise RuntimeError("desktop cache growth exceeds the declared graph allowance")
    finally:
        (output / "build.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({k:v for k,v in report.items() if k not in ("command","rebuiltTargets")}))


if __name__ == "__main__":
    main()
