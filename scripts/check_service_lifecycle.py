#!/usr/bin/env python3
"""Observe real file bytes stop on received ACL/guest revocation and expiry.

The large source is generated by its own OS. It is a runtime sample, not a
product size limit. Only public SDK file and management operations are used.
"""
import argparse
from pathlib import Path
import time
import threading
import json

from check_service_guests import GuestRunner


def deadline_witness(events, samples, source, provider, task, progressed_at, expires):
    """Bound the clock witness by public file observations, before postchecks."""
    observations = []
    for event in events:
        if event["host"] not in {source, provider} or event["op"] != "files_status":
            continue
        for status in event.get("answer", {}).get("result", {}).get("tasks", []):
            if status["id"] == task:
                observations.append(dict(host=event["host"], monotonic=event["monotonic"],
                    state=status["state"], bytes=status["bytes"]))
    progress = [value for value in observations if value["host"] == provider
        and value["state"] == "transferring" and value["bytes"] > 0
        and value["monotonic"] <= progressed_at]
    assert progress, "no actual receiver progress observation"
    progress = progress[-1]
    terminal = [value for value in observations if value["monotonic"] > progress["monotonic"]
        and value["state"] in {"complete", "failed", "cancelled"}]
    assert terminal, "no public terminal file observation"
    first_terminal = min(terminal, key=lambda value: value["monotonic"])
    crossings = [sample for sample in samples
        if progress["monotonic"] <= sample["monotonic"] <= first_terminal["monotonic"]
        and sample["unix"] >= expires]
    assert crossings, "no endpoint deadline crossing before the first terminal file observation"
    return dict(expires=expires, receiverProgress=progress, firstTerminal=first_terminal,
        firstCrossing=crossings[0], excludesPostTerminalChecks=True)


class LifecycleRunner(GuestRunner):
    def __init__(self, args):
        super().__init__(args)
        self.clock_samples = []
        self.clock_stop = threading.Event()
        def observe_clock():
            while not self.clock_stop.is_set():
                self.clock_samples.append(dict(monotonic=time.monotonic(), unix=time.time()))
                self.clock_stop.wait(0.025)
        self.clock_thread = threading.Thread(target=observe_clock, daemon=True)
        self.clock_thread.start()

    def cleanup(self):
        self.clock_stop.set()
        self.clock_thread.join(timeout=2)
        (self.output / "clock-samples.jsonl").write_text("".join(json.dumps(sample) + "\n" for sample in self.clock_samples))
        return super().cleanup()

    def interrupted_by_policy(self, sender, receiver, task, directory, cause):
        source = self.wait_task(sender, task)
        destination = self.wait_task(receiver, task)
        assert source["state"] in {"failed", "cancelled"} and source["receipt"] is None, source
        assert destination["state"] in {"failed", "cancelled"} and destination["receipt"] is None, destination
        assert 0 < destination["bytes"] < destination["size"], destination
        assert not self.listing(directory, receiver.remote)
        assert receiver.call("files_status")["enabled"] is True
        self.record(receiver.label, cause, dict(bytesBeforeStop=destination["bytes"], total=destination["size"],
            senderState=source["state"], receiverState=destination["state"], noReceipt=True,
            noSavedOrPartial=True, serviceStillEnabled=True, transport=destination["transport"]))

    def guest(self, issuer, provider, label, seconds):
        name = label + "-invite.json"
        issuer.call("guest_issue", path=self.path(name, issuer.remote), provider=provider.address, seconds=seconds)
        remote = not provider.remote if not self.local_only else False
        invitation = self.transfer(name, issuer.remote, remote)
        guest = self.start(label, remote, "join-guest", invitation)
        value = guest.call("guest_redeem")
        assert value["stage"] == "GuestActive"
        issuer.call("service_sync", address=provider.address)
        return guest, value["scope"]

    def scenario(self, prefix, creator_remote=False):
        role = "windows" if creator_remote else "linux"
        if self.lifecycle_role not in {"both", role}:
            return
        admin, provider = self.paired(prefix, creator_remote)
        directory = self.enable(provider, prefix)
        hosts = [provider, admin]
        if not self.expiry_only:
            caller = self.member(admin, prefix + "-caller", creator_remote)
            admin.call("service_sync", address=provider.address)
            caller.call("service_sync", address=admin.address)
            source, _ = self.generate(caller, prefix + "-live-member.bin", 512 * 1024**2)
            task = caller.call("file_send", address=provider.address, path=source)["task"]
            progress = self.wait_task(provider, task, terminal=False, progress=True)
            assert progress["receipt"] is None and 0 < progress["bytes"] < progress["size"]
            rule = dict(members=True, guests=True, allowed=[], denied=[caller.node])
            revision = admin.call("service_rule", provider=provider.node, service="files", previous=None, rule=rule)["revision"]
            admin.call("service_sync", address=provider.address)
            assert provider.call("service_status")["services"][0]["policy"]["revision"] == revision
            self.interrupted_by_policy(caller, provider, task, directory, "received_acl_stops_live_file")
            self.remove(source, caller.remote)
            provider.call("service_rule", provider=provider.node, service="files", previous=revision,
                rule=dict(members=True, guests=True, allowed=[], denied=[]))
            provider.call("service_sync", address=admin.address)
            guest, scope = self.guest(admin, provider, prefix + "-revoked-guest", 180)
            source, _ = self.generate(guest, prefix + "-live-guest.bin", 512 * 1024**2)
            task = guest.call("file_send", address=provider.address, path=source)["task"]
            self.pending(provider, task, guest)
            assert not self.listing(directory, provider.remote)
            provider.call("file_approve", task=task)
            self.wait_task(provider, task, terminal=False, progress=True)
            admin.call("guest_revoke", invitation=scope["invitation"])
            admin.call("service_sync", address=provider.address)
            self.interrupted_by_policy(guest, provider, task, directory, "received_guest_revocation_stops_live_file")
            self.remove(source, guest.remote)
            hosts.extend([caller, guest])
        expiring, scope = self.guest(admin, provider, prefix + "-expiring-guest", 180)
        # Include generation, Windows debug hashing and control scheduling in
        # one fixture budget. Measured512MiB preparation took17-26s, while a
        # five-second lead was crossed by a4.674s controller scheduling pause.
        # Doubling the file preserves in-flight I/O with a twelve-second lead;
        # delaying send leaves the existing60s approval wait sufficient.
        source, _ = self.generate(expiring, prefix + "-expiring.bin", 1024 * 1024**2)
        while (remaining := scope["created"] + 90 - time.time()) > 0:
            time.sleep(min(0.1, remaining))
        task = expiring.call("file_send", address=provider.address, path=source)["task"]
        self.pending(provider, task, expiring, preparation_timeout=90)
        assert not self.listing(directory, provider.remote)
        assert expiring.call("guest_status")["scope"]["expires"] == scope["expires"]
        # The source has already hashed its file and the real SDK stream waits
        # for confirmation. Approve near the original, unchanged deadline.
        while (remaining := scope["expires"] - time.time() - 12) > 0:
            time.sleep(min(0.1, remaining))
        assert time.time() < scope["expires"] - 1
        assert provider.call("file_approve", task=task)["approved"]
        progress = self.wait_task(provider, task, terminal=False, progress=True)
        assert 0 < progress["bytes"] < progress["size"]
        progressed_at = time.monotonic()
        self.interrupted_by_policy(expiring, provider, task, directory, "original_deadline_stops_live_file")
        # One endpoint is this Linux host in each actual-OS role. Observe its
        # real clock before the earliest public terminal file observation.
        # Directory and enabled-state postchecks cannot extend this boundary.
        witness = deadline_witness(self.events, self.clock_samples, expiring.label,
            provider.label, task, progressed_at, scope["expires"])
        self.record(provider.label, "original_deadline_clock_witness", dict(**witness,
            linuxParticipant="source" if not expiring.remote else "provider"))
        # Windows and Linux clocks have a measured offset. The provider may
        # expire first. Wait for the source's own public expiration precondition
        # before asserting that its local entry refuses another request.
        deadline = time.monotonic() + 60
        while True:
            status = expiring.call("guest_status")
            assert status["scope"]["expires"] == scope["expires"]
            lower_clock = time.monotonic() + min(sample["unix"] - sample["monotonic"] for sample in self.clock_samples)
            if status["stage"] == "GuestExpired" and lower_clock >= scope["expires"] + 1:
                break
            assert time.monotonic() < deadline, "source did not reach its original expiration"
            time.sleep(0.1)
        assert time.time() >= scope["expires"]
        assert status["stage"] == "GuestExpired"
        expiring.call("file_send", ok=False, address=provider.address, path=source)
        self.remove(source, expiring.remote)
        # Capacity and ordinary access remain usable after every cleanup.
        source, expected = self.generate(admin, prefix + "-after-cleanup.bin", 11)
        self.delivered(admin, provider, source, expected, directory)
        for host in [expiring, *hosts]:
            host.stop()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--linux", type=Path, required=True)
    parser.add_argument("--linux-sha", required=True)
    parser.add_argument("--windows", type=Path)
    parser.add_argument("--windows-sha")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--local-only", action="store_true")
    parser.add_argument("--role", choices=["both", "linux", "windows"], default="both")
    parser.add_argument("--expiry-only", action="store_true")
    args = parser.parse_args()
    args.focus = "smoke"
    args.failure_only = False
    if not args.local_only and not (args.windows and args.windows_sha):
        parser.error("actual Windows pin and hash required")
    if args.local_only and args.role == "windows":
        parser.error("Windows role requires the actual Windows endpoint")
    runner = LifecycleRunner(args)
    runner.lifecycle_role, runner.expiry_only = args.role, args.expiry_only
    runner.run()


if __name__ == "__main__":
    main()
