//! Reverse invitation delivery on an identified, control-only iroh session.
//! The scanned private capability authorizes this delivery; node IDs and route
//! hints alone do not. It never grants membership or releases a network secret.
use crate::{
    client_invitation::{BootstrapContact, ClientInvitation, MAX_INVITATION_BYTES},
    control_protocol::{AuthenticatedControl, OwnedControl},
};
use base64::{Engine, engine::general_purpose::URL_SAFE_NO_PAD};
use iroh::{
    EndpointAddr,
    endpoint::{ControlExchange, ControlMessageFormat},
};
use ring::hmac;
use serde::{Deserialize, Serialize};
use std::io;

pub const PAIRING_ALPN: &[u8] = b"miopunch/invitation-pairing/1";
const EXPORTER: &[u8] = b"miopunch/invitation-pairing/tls/1";
const DOMAIN: &[u8] = b"miopunch/invitation-pairing/delivery/1\0";
const MAX_DELIVERY: usize = MAX_INVITATION_BYTES * 2;

/// Private QR/link material generated by the receiving device. No Debug: the
/// capability is bearer authorization for invitation delivery to that device.
#[derive(Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PairingInfo {
    version: u32,
    pub(crate) address: EndpointAddr,
    capability: [u8; 32],
    pub(crate) bootstrap: BootstrapContact,
}
impl PairingInfo {
    pub(crate) fn new(address: EndpointAddr, bootstrap: BootstrapContact) -> Self {
        Self {
            version: 1,
            address,
            capability: rand::random(),
            bootstrap,
        }
    }
    pub fn encode(&self) -> io::Result<Vec<u8>> {
        self.validate()?;
        serde_json::to_vec(self).map_err(io::Error::other)
    }
    pub fn text(&self) -> io::Result<String> {
        Ok(format!(
            "miopunch://pair/{}",
            URL_SAFE_NO_PAD.encode(self.encode()?)
        ))
    }
    pub fn decode(bytes: &[u8]) -> io::Result<Self> {
        if bytes.len() > MAX_INVITATION_BYTES * 2 {
            return Err(rejected());
        }
        let decoded;
        let bytes = if let Some(value) = std::str::from_utf8(bytes)
            .ok()
            .map(str::trim)
            .and_then(|v| v.strip_prefix("miopunch://pair/"))
        {
            decoded = URL_SAFE_NO_PAD.decode(value).map_err(|_| rejected())?;
            decoded.as_slice()
        } else {
            bytes
        };
        if bytes.len() > MAX_INVITATION_BYTES {
            return Err(rejected());
        }
        let value: Self = serde_json::from_slice(bytes).map_err(|_| rejected())?;
        value.validate()?;
        Ok(value)
    }
    pub fn receiver(&self) -> iroh::EndpointId {
        self.address.id
    }
    pub fn address(&self) -> &EndpointAddr {
        &self.address
    }
    fn validate(&self) -> io::Result<()> {
        if self.version != 1 || self.address.addrs.len() > 32 {
            return Err(rejected());
        }
        self.bootstrap.validate()
    }
}
#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct Delivery {
    invitation: Vec<u8>,
    proof: Vec<u8>,
}

fn statement(
    connection: &(impl AuthenticatedControl + ?Sized),
    invitation: &[u8],
    receiver: iroh::EndpointId,
    sender: iroh::EndpointId,
) -> io::Result<Vec<u8>> {
    let mut binding = [0; 32];
    connection
        .export_keying_material(&mut binding, EXPORTER, b"")
        .map_err(|_| rejected())?;
    let mut bytes = DOMAIN.to_vec();
    bytes.extend_from_slice(receiver.as_bytes());
    bytes.extend_from_slice(sender.as_bytes());
    bytes.extend_from_slice(&binding);
    bytes.extend_from_slice(blake3::hash(invitation).as_bytes());
    Ok(bytes)
}
pub(crate) async fn deliver(
    connection: &(impl OwnedControl + ?Sized),
    local: iroh::EndpointId,
    info: &PairingInfo,
    invitation: &ClientInvitation,
) -> io::Result<()> {
    if connection.remote_id() != info.receiver() || connection.alpn() != PAIRING_ALPN {
        return Err(rejected());
    }
    let invitation = invitation.encode()?;
    let key = hmac::Key::new(hmac::HMAC_SHA256, &info.capability);
    let proof = hmac::sign(
        &key,
        &statement(connection, &invitation, connection.remote_id(), local)?,
    )
    .as_ref()
    .to_vec();
    let bytes = p2panda_core::cbor::encode_cbor(&Delivery { invitation, proof })
        .map_err(io::Error::other)?;
    if bytes.len() > MAX_DELIVERY {
        return Err(rejected());
    }
    let exchange = connection.open_control_exchange().await?;
    exchange
        .send_message(
            ControlMessageFormat::LengthPrefixed32 {
                maximum: MAX_DELIVERY,
            },
            &bytes,
        )
        .await?;
    exchange.finish_send().await?;
    if exchange
        .recv_message(ControlMessageFormat::Fixed { length: 4 })
        .await?
        != b"SAVE"
    {
        return Err(rejected());
    }
    Ok(())
}
pub(crate) struct ReceivedInvitation {
    pub invitation: ClientInvitation,
    pub bytes: Vec<u8>,
    exchange: ControlExchange,
}
impl ReceivedInvitation {
    /// Call only after the receiver has durably saved this exact invitation.
    pub async fn acknowledge(self) -> io::Result<()> {
        self.exchange
            .send_message(ControlMessageFormat::Fixed { length: 4 }, b"SAVE")
            .await?;
        self.exchange.finish_send().await
    }
}
pub(crate) async fn receive(
    connection: &(impl OwnedControl + ?Sized),
    local: iroh::EndpointId,
    info: &PairingInfo,
) -> io::Result<ReceivedInvitation> {
    if local != info.receiver() || connection.alpn() != PAIRING_ALPN {
        return Err(rejected());
    }
    let exchange = connection.accept_control_exchange().await?;
    let bytes = exchange
        .recv_message(ControlMessageFormat::LengthPrefixed32 {
            maximum: MAX_DELIVERY,
        })
        .await?;
    let delivery: Delivery =
        p2panda_core::cbor::decode_cbor(bytes.as_slice()).map_err(|_| rejected())?;
    let invitation = ClientInvitation::decode(&delivery.invitation)?;
    if invitation.contact() != connection.remote_id() {
        return Err(rejected());
    }
    hmac::verify(
        &hmac::Key::new(hmac::HMAC_SHA256, &info.capability),
        &statement(
            connection,
            &delivery.invitation,
            local,
            connection.remote_id(),
        )?,
        &delivery.proof,
    )
    .map_err(|_| rejected())?;
    Ok(ReceivedInvitation {
        invitation,
        bytes: delivery.invitation,
        exchange,
    })
}

/// A dedicated pre-admission receiver exposes only the bounded pairing wire.
/// It cannot return a member/business handle, even to a TLS-authenticated peer.
#[derive(Clone, Debug)]
pub(crate) struct PairingGate;
impl iroh::endpoint::EndpointAdmission for PairingGate {
    async fn admit(
        &self,
        connection: &iroh::endpoint::ControlConnection,
    ) -> io::Result<iroh::endpoint::AdmissionOutcome> {
        if connection.alpn() != PAIRING_ALPN {
            return Err(rejected());
        }
        let budget = crate::connection_budget::remaining(connection.caller_deadline());
        n0_future::time::timeout(budget, async {
            let exchange = if connection.side().is_client() {
                connection.open_control_exchange().await?
            } else {
                connection.accept_control_exchange().await?
            };
            exchange
                .send_message(ControlMessageFormat::Fixed { length: 1 }, &[1])
                .await?;
            exchange.finish_send().await?;
            if exchange
                .recv_message(ControlMessageFormat::Fixed { length: 1 })
                .await?
                != [1]
            {
                return Err(rejected());
            }
            Ok::<_, io::Error>(())
        })
        .await
        .map_err(|_| rejected())??;
        Ok(
            iroh::endpoint::AdmissionOutcome::ControlOnlyWithConfirmation(
                iroh::endpoint::ControlConfirmation::with_control(|control| {
                    Box::pin(async move {
                        if control.alpn() == PAIRING_ALPN {
                            Ok(())
                        } else {
                            Err(rejected())
                        }
                    })
                }),
            ),
        )
    }
    fn is_current(&self, connection: &iroh::endpoint::ControlConnection) -> bool {
        connection.alpn() == PAIRING_ALPN
    }
}
fn rejected() -> io::Error {
    io::Error::new(
        io::ErrorKind::PermissionDenied,
        "invitation pairing rejected",
    )
}
